/** Etiqueta de un valor de enum: R[`op${v}`], R[`type${v}`]… */
export function enumLabel(R: RealtyDict, prefix: "op" | "opBuy" | "type" | "st" | "feat" | "ch" | "cst" | "ap" | "bal" | "rate" | "pi" | "prio", value: string | null | undefined): string {
  if (!value) return R.any;
  const v = (R as unknown as Record<string, unknown>)[`${prefix}${value}`];
  return typeof v === "string" ? v : value;
}
