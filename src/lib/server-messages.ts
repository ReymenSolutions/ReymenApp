const PLAN_RESOURCE_EN: Record<string, string> = {
  leads: "leads",
  usuarios: "users",
  automatizaciones: "automations",
};

// Mensajes con partes variables: [patrón en español, versión en inglés].
const EN_PATTERNS: [RegExp, (...groups: string[]) => string][] = [
  [
    /^Alcanzaste el límite de (.+) de tu plan \((\d+)\)\. Solicita más capacidad en Configuración\.$/,
    (resource, limit) => `You reached your plan's ${PLAN_RESOURCE_EN[resource] ?? resource} limit (${limit}). Request more capacity in Settings.`,
  ],
  [
    /^El Laboratorio de IA no pudo generar una respuesta: ([\s\S]*)$/,
    (rest) => `The AI Lab couldn't generate a reply: ${rest.replace("n8n no configurado", "n8n not configured")}`,
  ],
  [/^Máximo (\d+) fotos por propiedad\.$/, (n) => `Maximum ${n} photos per listing.`],
  [/^Alcanzaste el máximo de (\d+) sucursales$/, (max) => `You reached the maximum of ${max} branches`],
  [/^Alcanzaste el máximo de (\d+) campos personalizados$/, (max) => `You reached the maximum of ${max} custom fields`],
  [/^El valor de «(.+)» no es válido$/, (label) => `The value of "${label}" isn't valid`],
  [/^Parámetros del template no válidos: (.+)$/, (details) => `Invalid template parameters: ${details}`],
  [/^Tu plan incluye (\d+) agentes? IA activos?; apaga uno o mejora tu plan$/, (n) => `Your plan includes ${n} active AI ${n === "1" ? "agent" : "agents"}; turn one off or upgrade your plan`],
  [/^La versión (.+) ya existe$/, (version) => `Version ${version} already exists`],
  [/^No hay un precio de Stripe configurado para el plan (.+)$/, (plan) => `There's no Stripe price configured for the ${plan} plan`],
  [/^Tu organización no tiene el módulo "(.+)" habilitado\.$/, (module) => `Your organization doesn't have the "${module}" module enabled.`],
  [/^Datos inválidos: ([\s\S]+)$/, (detail) => `Invalid data: ${EN[detail] ?? detail}`],
];

export function translateServerMessage(message: string, lang: "es" | "en"): string {
  if (lang === "es") return ES[message] ?? message;
  const exact = EN[message];
  if (exact) return exact;
  for (const [pattern, build] of EN_PATTERNS) {
    const m = message.match(pattern);
    if (m) return build(...m.slice(1));
  }
  return message;
}
